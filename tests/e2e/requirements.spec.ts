import { expect, test } from "@playwright/test";

test("gợi ý JD, xác nhận nguồn, giải thích và giữ nguyên đánh giá cũ", async ({ page }, testInfo) => {
  await page.goto("/profile");
  await page.getByLabel("Kỹ năng").fill("HTML");
  await page.getByLabel("Số tháng kinh nghiệm", { exact: false }).fill("6");
  await page.getByRole("button", { name: "Lưu hồ sơ", exact: true }).click();
  await expect(page).toHaveURL(/\/journey$/);
  await page.goto("/jobs?job=new");
  await page.getByLabel("Tên vị trí").fill("Thực tập JD nguồn");
  await page.getByLabel("Doanh nghiệp", { exact: true }).fill("Công ty Nguồn");
  const jd = "Yêu cầu bắt buộc:\n- Biết HTML\n- Tối thiểu 6 tháng kinh nghiệm\n- Lịch làm việc linh hoạt\nƯu tiên:\n- Biết React\n- Java hoặc Python\nChế độ đãi ngộ sẽ trao đổi";
  await page.getByLabel("Nội dung JD gốc", { exact: false }).fill(jd);
  await page.getByRole("button", { name: "Gợi ý yêu cầu từ JD" }).click();
  await expect(page.getByRole("status")).toContainText("Có 5 gợi ý");
  await page.getByRole("button", { name: "Thêm 5 gợi ý vào yêu cầu" }).click();
  await expect(page.locator("fieldset.requirement")).toHaveCount(5);
  await page.getByRole("button", { name: "Lưu tin", exact: true }).click();
  await expect(page).not.toHaveURL(/job=new(?:&|$)/);
  await expect(page).toHaveURL(/\/jobs\?job=/);
  const jobId = new URL(page.url()).searchParams.get("job")!;
  await expect(page.getByLabel("Nội dung JD gốc", { exact: false })).toHaveValue(jd);
  await page.getByRole("button", { name: "Xác nhận yêu cầu và xem mức độ phù hợp" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Hãy kiểm tra và xác nhận từng tiêu chí" })).toBeVisible();
  for (let index = 1; index <= 5; index++) await page.getByRole("checkbox", { name: `Đã kiểm tra tiêu chí ${index}`, exact: true }).check();
  await page.getByLabel("Nội dung yêu cầu").first().fill("HTML5");
  await expect(page.getByRole("checkbox", { name: "Đã kiểm tra tiêu chí 1", exact: true })).not.toBeChecked();
  await page.getByLabel("Nội dung yêu cầu").first().fill("HTML");
  await page.getByRole("checkbox", { name: "Đã kiểm tra tiêu chí 1", exact: true }).check();
  await page.getByRole("button", { name: "Xác nhận yêu cầu và xem mức độ phù hợp" }).click();
  await expect(page).toHaveURL(new RegExp(`/jobs/${jobId}/match$`));
  await expect(page.getByText("80%", { exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Phạm vi kết quả đánh giá" })).toContainText("3 / 5 tiêu chí đủ thông tin");
  await expect(page.getByText("Còn 2 tiêu chí cần bổ sung hoặc xác nhận", { exact: false })).toBeVisible();
  await expect(page.locator(".clarification-question")).toHaveCount(2);
  await expect(page.locator(".jd-source")).toHaveCount(5);
  await expect(page.getByText("Kỹ năng này xuất hiện trong hồ sơ đã khai báo.", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("assessment-desktop.png"), fullPage: true });
  await page.getByLabel("Mức đáp ứng cho HTML", { exact: true }).selectOption("UNKNOWN");
  await page.getByRole("button", { name: "Lưu để xem sau", exact: true }).click();
  await expect(page.getByText("67%", { exact: true })).toBeVisible();
  await expect(page.getByText("Bạn đã đánh dấu cần thêm thông tin trước khi kết luận tiêu chí này.", { exact: true })).toBeVisible();
  await page.goto("/journey");
  const result = page.locator(`a[href^="/jobs/${jobId}/match?assessment="]`);
  const savedHref = (await result.getAttribute("href"))!;
  await page.goto("/profile");
  await page.getByLabel("Kỹ năng").fill("HTML, React");
  await page.getByRole("button", { name: "Lưu hồ sơ", exact: true }).click();
  await expect(page).toHaveURL(/\/journey$/);
  await page.goto(savedHref);
  await expect(page.getByText(/Đây là kết quả đã ghi nhận trước khi hồ sơ hoặc JD thay đổi/)).toBeVisible();
  await expect(page.getByText("67%", { exact: true })).toBeVisible();
  const htmlItem = page.locator(".assessment-item").filter({ has: page.getByText("HTML", { exact: true }) });
  await htmlItem.getByText("Hồ sơ tại lần đối chiếu", { exact: true }).click();
  await expect(htmlItem.getByText("Kỹ năng đã khai báo: HTML.", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Mở kết quả hiện tại", exact: true }).click();
  await expect(page.getByText("100%", { exact: true })).toBeVisible();
  await expect(page.getByText("Còn 2 tiêu chí cần bổ sung hoặc xác nhận", { exact: false })).toBeVisible();
  await page.setViewportSize({ width: 360, height: 800 });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth)).toBeLessThanOrEqual(360);
  await page.screenshot({ path: testInfo.outputPath("assessment-mobile.png"), fullPage: true });
  await page.getByRole("link", { name: "Sửa yêu cầu tuyển dụng", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Đã kiểm tra tiêu chí 1", exact: true })).toBeChecked();
  expect(await page.locator("body").evaluate((body) => body.scrollWidth)).toBeLessThanOrEqual(360);
  await page.getByLabel("Nội dung JD gốc", { exact: false }).fill(jd.replace("Biết HTML", "Biết CSS"));
  await expect(page.getByRole("checkbox", { name: "Đã kiểm tra tiêu chí 1", exact: true })).not.toBeChecked();
  for (let index = 1; index <= 5; index++) await page.getByRole("checkbox", { name: `Đã kiểm tra tiêu chí ${index}`, exact: true }).check();
  await page.getByRole("button", { name: "Xác nhận yêu cầu và xem mức độ phù hợp" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Một số đoạn trích không còn nằm trong JD gốc" })).toBeVisible();
});
