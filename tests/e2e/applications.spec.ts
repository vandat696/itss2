import { expect, test } from "@playwright/test";

test("theo dõi từ JD, lịch phỏng vấn, lịch sử, chống trùng và xóa đơn", async ({ page }, testInfo) => {
  await page.goto("/applications");
  await expect(page.getByRole("heading", { name: "Theo dõi ứng tuyển", exact: true })).toBeVisible();
  await expect(page.getByText("Bắt đầu từ một đơn đã gửi.")).toBeVisible();
  await page.goto("/jobs?job=frontend-demo");
  await page.getByRole("link", { name: /Đã nộp hồ sơ/ }).click();
  await expect(page.getByLabel("Vị trí ứng tuyển")).toHaveValue("Thực tập sinh Frontend");
  await page.getByLabel("Ngày nộp hồ sơ").fill("2020-01-01");
  await page.getByLabel("Ngày theo dõi tiếp").fill("2020-01-02");
  await page.getByLabel("Ghi chú").fill("Đã gửi CV và portfolio.");
  await page.getByRole("button", { name: "Lưu đơn ứng tuyển", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã lưu đơn ứng tuyển");
  const applicationPath = new URL(page.url()).pathname;
  const history = page.locator("section").filter({ has: page.getByRole("heading", { name: "Lịch sử trạng thái", exact: true }) });
  await expect(history.locator("li")).toHaveCount(1);
  await page.getByLabel("Trạng thái đơn").selectOption("INTERVIEW");
  await page.getByLabel("Lịch phỏng vấn").fill("2099-11-16T09:30");
  await page.getByLabel("Người liên hệ").fill("Chị Linh · hr@example.com");
  await page.getByLabel("Ghi chú").fill("Chuẩn bị trình bày dự án React.");
  await page.getByRole("button", { name: "Lưu cập nhật", exact: true }).click();
  await expect(history.locator("li")).toHaveCount(2);
  await expect(history.getByText("Đã gửi CV và portfolio.")).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Lịch phỏng vấn")).toHaveValue("2099-11-16T09:30");
  await expect(page.getByLabel("Người liên hệ")).toHaveValue("Chị Linh · hr@example.com");
  await page.getByLabel("Ghi chú").fill("Mang theo bản CV mới.");
  await page.getByRole("button", { name: "Lưu cập nhật", exact: true }).click();
  await expect(history.locator("li")).toHaveCount(2);
  await page.goto("/applications");
  await expect(page.locator(".application-card")).toContainText("Cần theo dõi");
  await expect(page.locator(".application-agenda")).toContainText("09:30");
  await page.screenshot({ path: testInfo.outputPath("applications-desktop.png"), fullPage: true });
  await page.getByRole("navigation", { name: "Lọc đơn ứng tuyển" }).getByRole("link", { name: /Phỏng vấn/ }).click();
  await expect(page.locator(".application-card")).toHaveCount(1);
  await page.goto("/applications/new?job=frontend-demo");
  await expect(page).toHaveURL(new RegExp(applicationPath + "$"));
  await page.goto("/applications/new");
  await page.getByLabel("Tin tuyển dụng liên quan").selectOption("frontend-demo");
  await page.getByRole("button", { name: "Lưu đơn ứng tuyển", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Tin này đã có đơn theo dõi" })).toBeVisible();
  await page.goto(applicationPath);
  await page.getByLabel("Trạng thái đơn").selectOption("OFFER");
  await page.getByRole("button", { name: "Lưu cập nhật", exact: true }).click();
  await expect(history.locator("li")).toHaveCount(3);
  await page.goto("/applications");
  await expect(page.locator(".application-agenda")).toContainText("Chưa có lịch phỏng vấn sắp tới");
  await expect(page.locator(".follow-up-entry")).toHaveCount(0);
  await page.goto("/journey");
  await page.getByRole("link", { name: /Thực tập sinh Frontend.*Nhận đề nghị/ }).click();
  page.once("dialog", (dialog) => dialog.dismiss());
  await page.getByRole("button", { name: "Xóa đơn", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(applicationPath + "$"));
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "Xóa đơn", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã xóa đơn ứng tuyển");
  await expect(page.locator(".application-card")).toHaveCount(0);
  await page.goto(applicationPath);
  await expect(page.getByRole("heading", { name: "404", exact: true })).toBeVisible();
});

test("nhập đơn riêng, tìm kiếm, bộ lọc trống và UI mobile", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto("/applications/new");
  await page.getByLabel("Vị trí ứng tuyển").fill("Thực tập thiết kế giao diện sản phẩm");
  await page.getByLabel("Doanh nghiệp", { exact: true }).fill("Công ty Thiết kế Sáng tạo");
  await page.getByLabel("Trạng thái đơn").selectOption("SCREENING");
  await page.getByLabel("Ghi chú").fill("Portfolio Figma đã gửi.");
  await page.getByRole("button", { name: "Lưu đơn ứng tuyển", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã lưu đơn ứng tuyển");
  expect(await page.locator("body").evaluate((body) => body.scrollWidth)).toBeLessThanOrEqual(360);
  await page.getByRole("link", { name: "Về danh sách ứng tuyển", exact: true }).click();
  await page.getByLabel("Tìm đơn ứng tuyển").fill("Figma");
  await page.getByRole("button", { name: "Tìm", exact: true }).click();
  await expect(page.locator(".application-card")).toHaveCount(1);
  await page.getByRole("navigation", { name: "Lọc đơn ứng tuyển" }).getByRole("link", { name: /Nhận đề nghị/ }).click();
  await expect(page.getByText("Chưa có đơn phù hợp với bộ lọc")).toBeVisible();
  await page.getByRole("link", { name: "Xem tất cả đơn", exact: true }).click();
  await expect(page.locator(".application-card").filter({ hasText: "Công ty Thiết kế Sáng tạo" })).toHaveCount(1);
  expect(await page.locator("body").evaluate((body) => body.scrollWidth)).toBeLessThanOrEqual(360);
  await page.screenshot({ path: testInfo.outputPath("applications-mobile.png"), fullPage: true });
});
